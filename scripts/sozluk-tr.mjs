/** Kalıp + isim sözlüğüyle çöz; olmazsa null. */
export function kalipCevir(etiket) {
  let t = String(etiket ?? "").trim();
  if (!t) return null;

  // sondaki ", max." / " max." ayrılır, sonuna "azami" eklenir
  let azami = false;
  const m = t.match(/^(.*?),?\s*max\.?$/i);
  if (m && m[1] && /max/i.test(t)) { t = m[1].trim(); azami = true; }

  for (const [kalip, kur] of KALIPLAR) {
    const g = t.match(kalip);
    if (!g) continue;
    const isim = ISIM[g[1].trim().toLowerCase()];
    if (!isim) return null;
    const sonuc = kur(isim);
    return azami ? `Azami ${sonuc}` : sonuc;
  }
  return null;
}

