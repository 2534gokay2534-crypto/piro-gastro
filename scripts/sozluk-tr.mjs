const SAYISAL = /^[\d\s.,+°/x×"'-]*(mm|cm|m|kg|g|l|ml|w|kw|v|hz|bar|°c|°f|rpm|%|min|h|gn|nac|"|inch)?[\d\s.,+°/x×"'-]*$/i;

/**
 * Dilden bağımsız kodlar — çevrilmez, olduğu gibi geçer.
 * Norm/standart (EN 631, DIN, ISO), koruma sınıfı (IPX3), soğutucu gazı
 * (R290), ölçü (3/4"), model/seri adları.
 */
const KOD = /^(EN|DIN|ISO|NSF|CE|UL)\s*\d|^IPX?\d|^R\d{2,4}|^[A-Z]{1,3}\d{2,}|^\d+\/\d+"|^GN\s|^Ø/i;

/** "Stainless steel ,Plastic" gibi birleşik değerleri parçala */
const AYIRICI = /\s*,\s*/;

export function degerCevir(v) {
  const t = String(v ?? "").trim();
  if (!t) return t;
  if (DEGER[t]) return DEGER[t];
  if (SAYISAL.test(t)) return t;
  if (KOD.test(t)) return t;

  // birleşik değer: her parçayı ayrı çöz, hepsi çözülürse birleştir
  if (AYIRICI.test(t)) {
    const parcalar = t.split(AYIRICI).map((x) => x.trim()).filter(Boolean);
    if (parcalar.length > 1 && parcalar.length <= 4) {
      const cevrilen = parcalar.map((x) =>
        DEGER[x] ?? (SAYISAL.test(x) || KOD.test(x) ? x : null),
      );
      if (cevrilen.every(Boolean)) return cevrilen.join(", ");
    }
  }
  return null;                              // çevrilemedi
}

export function etiketCevir(l) {
  const t = String(l ?? "").trim();
  return ETIKET[t] ?? kalipCevir(t) ?? null;
}

